import { test, expect } from '@playwright/test'

test('uploads and switches variants, changes placement and compares actual widths', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByLabel('Channel name', { exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'A better thumbnail starts here.' })).toBeVisible()
  await expect(page.locator('.video-card')).toHaveCount(7)
  const details = await page.locator('.editor-section').boundingBox()
  const thumbnails = await page.locator('.variant-list').boundingBox()
  expect(details!.y).toBeLessThan(thumbnails!.y)
  const options = await page.locator('.preview-options').boundingBox()
  const preview = await page.locator('.youtube-preview').boundingBox()
  expect(options!.y).toBeLessThan(preview!.y)
  await page.locator('input[type=file]').setInputFiles('public/demo/camera.jpg')
  await expect(page.locator('.variant')).toHaveCount(3)
  await expect(page.locator('.proposed img')).toHaveAttribute('src', /^blob:/)
  await page.getByLabel('Video title', { exact: true }).fill('My new thumbnail')
  await expect(page.locator('.proposed h3')).toHaveText('My new thumbnail')
  await page.getByLabel('Feed position').selectOption('1')
  await expect(page.locator('.video-card').first()).toHaveClass(/proposed/)
  await page.getByRole('tab', { name: 'Compare' }).click()
  await expect(page.locator('.comparison-row')).toHaveCount(3)
  await expect(page.locator('.comparison-cards').first().locator('> div')).toHaveCount(3)
  expect(await page.locator('.comparison-cards').first().locator('> div').first().evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(360)
  await page.getByRole('button', { name: 'Remove camera', exact: true }).click()
  await expect(page.locator('.variant')).toHaveCount(2)
  expect(errors).toEqual([])
})

test('live search passes query and session key and renders supplied results', async ({ page }) => {
  await page.route('**/api/search', async route => {
    expect(route.request().postDataJSON()).toMatchObject({ query: 'acoustic rock covers', apiKey: 'test-session-key', region: 'US' })
    await route.fulfill({ json: { videos: [{ id: 'live-1', title: 'A live search competitor', channel: 'Test channel', thumbnail: '/demo/room.jpg', views: '10K views', published: '2026-10-10', duration: '4:30' }] } })
  })
  await page.goto('/')
  await expect(page.getByLabel('Channel name', { exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Connect YouTube' }).click()
  await page.getByLabel('YouTube Data API key').fill('test-session-key')
  await page.getByRole('button', { name: 'Connect & search' }).click()
  await expect(page.getByText('Live results · acoustic rock covers')).toBeVisible()
  await expect(page.locator('.video-card')).toHaveCount(2)
  await expect(page.getByRole('heading', { name: 'A live search competitor' })).toBeVisible()
  await page.getByRole('tab', { name: 'Search results' }).click()
  await expect(page.locator('.youtube-preview')).toHaveClass(/search-layout/)
  await page.getByRole('button', { name: 'Use dark preview' }).click()
  await expect(page.locator('.youtube-preview')).toHaveClass(/dark/)
  await page.getByLabel('Hide thumbnail labels').check()
  await expect(page.locator('.proposal-tag')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('frame.youtubeApiKey'))).toBe('test-session-key')
  await page.getByLabel('Hide thumbnail borders').check()
  await expect(page.locator('.proposed')).toHaveClass(/hide-border/)
  expect(await page.locator('.proposed .video-image').evaluate(el => getComputedStyle(el).boxShadow)).toBe('none')
})

test('mobile viewport remains within screen and all layouts are usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByLabel('Channel name', { exact: true })).toBeEnabled()
  for (const name of ['Home feed', 'Search results', 'Mobile', 'Compare']) {
    await page.getByRole('tab', { name, exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  }
})

test('API rejects missing keys, invalid queries, and cross-origin requests', async ({ request }) => {
  const missing = await request.post('/api/search', { data: { query: 'desk setup' } })
  expect(missing.status()).toBe(400)
  const invalid = await request.post('/api/search', { data: { query: '' } })
  expect(invalid.status()).toBe(400)
  const crossOrigin = await request.post('/api/search', { headers: { Origin: 'https://another.example' }, data: { query: 'desk' } })
  expect(crossOrigin.status()).toBe(403)
  const config = await request.get('/api/youtube-config')
  expect(await config.json()).toEqual({ configured: false })
})


test('channel, region, and API key survive reload without exposing the saved key in the textbox', async ({ page }) => {
  const keys: string[] = []
  await page.route('**/api/search', async route => {
    keys.push(route.request().postDataJSON().apiKey)
    await route.fulfill({ json: { videos: [] } })
  })
  await page.goto('/')
  await expect(page.getByLabel('Channel name', { exact: true })).toBeEnabled()
  await page.getByLabel('Channel name', { exact: true }).fill('My acoustic channel')
  await page.getByLabel('Search region').selectOption('BR')
  await page.getByRole('button', { name: 'Connect YouTube' }).click()
  await page.getByLabel('YouTube Data API key').fill('saved-test-key')
  await page.getByRole('button', { name: 'Connect & search' }).click()
  await expect(page.getByText('Live results · acoustic rock covers')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Channel name', { exact: true })).toHaveValue('My acoustic channel')
  await expect(page.getByLabel('Search region')).toHaveValue('BR')
  await page.getByRole('button', { name: 'API connected' }).click()
  await expect(page.getByLabel('YouTube Data API key')).toHaveValue('')
  await expect(page.getByLabel('YouTube Data API key')).toHaveAttribute('placeholder', /Saved key/)
  await page.getByRole('button', { name: 'Connect & search' }).click()
  await expect(page.getByText('Live results · acoustic rock covers')).toBeVisible()
  expect(keys).toEqual(['saved-test-key', 'saved-test-key'])
  await page.getByRole('button', { name: 'API connected' }).click()
  await page.getByLabel('YouTube Data API key').fill('replacement-test-key')
  await page.getByRole('button', { name: 'Connect & search' }).click()
  await expect(page.getByText('Live results · acoustic rock covers')).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('frame.youtubeApiKey'))).toBe('replacement-test-key')
  await page.getByRole('button', { name: 'API connected' }).click()
  await page.getByRole('button', { name: 'Forget saved key' }).click()
  expect(await page.evaluate(() => localStorage.getItem('frame.youtubeApiKey'))).toBeNull()
  await expect(page.getByLabel('YouTube Data API key')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Connect & search' })).toBeDisabled()
})
